  function isMarkedInstalled(){
    try{ return localStorage.getItem(INSTALLED_KEY) === '1'; }catch(e){ return false; }
  }
  function markInstalled(){
    try{ localStorage.setItem(INSTALLED_KEY, '1'); }catch(e){}
  }

